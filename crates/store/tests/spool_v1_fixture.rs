//! T17-04 acceptance test: "old spool versions import" (spec 11 §4 `[FIXED
//! concern]`: "a daemon MUST be able to import all spool `format_version`s ≤
//! its own").
//!
//! `local_rag_core::spool::FORMAT_VERSION` has been `1` since it was
//! introduced and has never been bumped, so there is no real *older* version
//! to import today — the behavioral gap this card names does not exist yet.
//! What this test establishes instead is the **pattern** and the **anchor**:
//! a real, byte-frozen format-version-1 segment, captured once by running
//! today's encoder and pasted here as a literal, decoded by whatever decoder
//! ships in the future. This must **not** be regenerated by calling the live
//! encoder inside the test — the day `FORMAT_VERSION` bumps to 2, the live
//! encoder itself starts emitting v2, and a live-generated "v1 fixture" would
//! silently follow it, defeating the entire point. When that bump happens,
//! add a new `V2_SEGMENT_BYTES` fixture alongside this one (captured the same
//! way, once, under the `FORMAT_VERSION == 2` encoder) rather than editing
//! this one.

