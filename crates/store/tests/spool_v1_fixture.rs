fn open_state() -> (TempHome, StoreLayout, StateDb) {
    let home = TempHome::new().expect("temp home");
    let layout = StoreLayout::new(home.join("local-rag"));
    layout.ensure().expect("ensure store tree");
    let db = StateDb::open(layout.state_db()).expect("open state.sqlite");
    (home, layout, db)
}

struct FixedUuid;
impl UuidSource for FixedUuid {
    fn next_uuid(&self) -> local_rag_core::identity::Uuid {
        uuidv7_from(1_700_000_000_000, [0xCD; 10])
    }
}

/// A real, frozen format-version-1 spool segment still imports cleanly under
/// today's (still format-version-1) decoder — the anchor this module's doc
/// comment describes.
#[tokio::test]
async fn a_real_v1_spool_segment_still_imports_at_head() {
    let (_home, layout, db) = open_state();
    let session_dir = layout.spool_session("v1-fixture-session");
    std::fs::create_dir_all(&session_dir).expect("session dir");
    std::fs::write(session_dir.join("000001.seg"), V1_SEGMENT_BYTES).expect("write v1 fixture");

    let outcome = import_session_tail(
        &db,
        &layout,
        "v1-fixture-session",
        &RequestRoot::default(),
        &FixedUuid,
        1_700_000_000_000,
        72,
    )
    .await
    .expect("a real v1 segment imports without error");

    assert!(
        outcome.stalled_on.is_none(),
        "a real v1 segment must not stall: {:?}",
        outcome.stalled_on
    );
    assert_eq!(outcome.report.imported, 1, "the one frame is imported");
    assert_eq!(outcome.report.exact_duplicates, 0);
    assert_eq!(outcome.report.window_duplicates, 0);
    assert!(outcome.report.saw_stop, "the frame's event_type is Stop");

    let read = db.open_read().expect("read conn");
    let (event_type, session_id, evidence_kind): (String, String, String) = read
        .query_row(
            "SELECT event_type, session_id, evidence_kind FROM observation_envelope \
             WHERE source_event_id = 'st:v1-fixture-session:1'",
            [],
            |r| Ok((r.get(0)?, r.get(1)?, r.get(2)?)),
        )
        .expect("the v1 fixture's envelope row is present");
    assert_eq!(event_type, "Stop");
    assert_eq!(session_id, "v1-fixture-session");
    assert_eq!(evidence_kind, "model_claim");
}
